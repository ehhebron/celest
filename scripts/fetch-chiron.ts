/**
 * Regenerates src/astro/data/chironTable.ts from JPL Horizons.
 *
 * Chiron is not part of astronomy-engine, so we tabulate its heliocentric
 * J2000 equatorial (ICRF) position every 20 days from 1799-11 to 2150-03 and
 * interpolate at runtime. Values are stored as integer micro-AU.
 *
 *   node scripts/fetch-chiron.ts
 */
import { writeFileSync } from 'node:fs'

const START = '1799-11-01'
const STOP = '2150-03-01'
const STEP_DAYS = 20

const params = new URLSearchParams({
  format: 'text',
  COMMAND: "'2060;'",
  OBJ_DATA: "'NO'",
  MAKE_EPHEM: "'YES'",
  EPHEM_TYPE: "'VECTORS'",
  CENTER: "'500@10'",
  REF_PLANE: "'FRAME'",
  REF_SYSTEM: "'ICRF'",
  VEC_TABLE: "'1'",
  START_TIME: `'${START}'`,
  STOP_TIME: `'${STOP}'`,
  STEP_SIZE: `'${STEP_DAYS} d'`,
  CSV_FORMAT: "'YES'",
  VEC_LABELS: "'NO'",
  OUT_UNITS: "'AU-D'",
  VEC_CORR: "'NONE'",
})

const res = await fetch(`https://ssd.jpl.nasa.gov/api/horizons.api?${params}`)
const text = await res.text()
const body = text.split('$$SOE')[1]?.split('$$EOE')[0]
if (!body) throw new Error('Unexpected Horizons response:\n' + text.slice(0, 2000))

const rows = body
  .trim()
  .split('\n')
  .map((line) => line.split(',').map((s) => s.trim()))
const jd0 = Number(rows[0][0])
const xs: number[] = []
const ys: number[] = []
const zs: number[] = []
for (const r of rows) {
  xs.push(Math.round(Number(r[2]) * 1e6))
  ys.push(Math.round(Number(r[3]) * 1e6))
  zs.push(Math.round(Number(r[4]) * 1e6))
}

const out = `// Generated by scripts/fetch-chiron.ts from JPL Horizons (2060 Chiron, DE441).
// Heliocentric ICRF/J2000 equatorial position, integer micro-AU, TDB.
export const CHIRON_JD0_TDB = ${jd0}
export const CHIRON_STEP_DAYS = ${STEP_DAYS}
export const CHIRON_X = [${xs.join(',')}]
export const CHIRON_Y = [${ys.join(',')}]
export const CHIRON_Z = [${zs.join(',')}]
`
writeFileSync(new URL('../src/astro/data/chironTable.ts', import.meta.url), out)
console.log(`Wrote ${rows.length} rows starting JD ${jd0}`)
